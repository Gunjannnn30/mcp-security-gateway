"""Runtime monitoring of MCP tool behaviour.

Collects system- and network-level events generated by a tool process while
it runs. On Linux this is the place to hook eBPF (Tetragon/BCC/libbpf); on
other platforms we fall back to psutil-based process observation so the
prototype stays runnable everywhere.
"""

from __future__ import annotations

import os
import platform
import subprocess
import sys
import time
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

import psutil


@dataclass
class RuntimeEvent:
    timestamp: float
    event_type: str  # file_access | network_connect | process_spawn | other
    detail: str
    process_id: Optional[int] = None


class RuntimeMonitor:
    def __init__(self) -> None:
        self.platform = platform.system().lower()
        self._ebpf_available = self._check_ebpf()

    def _check_ebpf(self) -> bool:
        """eBPF-based monitoring is only meaningful on Linux with the right
        tooling (bpftrace/BCC/Tetragon). Return True only if we can use it."""
        if self.platform != "linux":
            return False
        # Best-effort: check for common eBPF tooling without requiring it.
        for cmd in ("bpftrace", "bcc", "tetragon"):
            if self._which(cmd):
                return True
        return False

    @staticmethod
    def _which(cmd: str) -> bool:
        import shutil

        return shutil.which(cmd) is not None

    def run_and_monitor(
        self,
        cmd: List[str],
        *,
        timeout: float = 30.0,
        watch_paths: Optional[List[str]] = None,
    ) -> tuple[int, str, str, List[RuntimeEvent]]:
        """Run a command, collect runtime events, return
        (returncode, stdout, stderr, events)."""
        events: List[RuntimeEvent] = []
        watch_paths = watch_paths or []

        proc = subprocess.Popen(
            cmd,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
        )

        # Observe the process tree with psutil while it runs.
        try:
            parent = psutil.Process(proc.pid)
        except psutil.Error:
            parent = None

        start = time.time()
        while True:
            if proc.poll() is not None:
                break
            if time.time() - start > timeout:
                proc.kill()
                break
            if parent:
                try:
                    for child in parent.children(recursive=True):
                        self._observe_process(child, events, watch_paths)
                    self._observe_process(parent, events, watch_paths)
                except psutil.Error:
                    pass
            time.sleep(0.2)

        try:
            out, err = proc.communicate(timeout=5)
        except subprocess.TimeoutExpired:
            proc.kill()
            out, err = proc.communicate()
        return proc.returncode or 0, out or "", err or "", events

    def _observe_process(
        self,
        proc: psutil.Process,
        events: List[RuntimeEvent],
        watch_paths: List[str],
    ) -> None:
        try:
            # File descriptors -> infer file access / network connections.
            try:
                connections = proc.connections(kind="inet")
                for conn in connections:
                    if conn.status == psutil.CONN_ESTABLISHED:
                        raddr = conn.raddr
                        target = f"{raddr.ip}:{raddr.port}" if raddr else "?"
                        events.append(
                            RuntimeEvent(
                                timestamp=time.time(),
                                event_type="network_connect",
                                detail=target,
                                process_id=proc.pid,
                            )
                        )
            except (psutil.AccessDenied, psutil.Error):
                pass

            try:
                open_files = proc.open_files()
                for f in open_files:
                    path = f.path
                    if any(fnmatch(path, wp) for wp in watch_paths) or watch_paths == ["*"]:
                        events.append(
                            RuntimeEvent(
                                timestamp=time.time(),
                                event_type="file_access",
                                detail=path,
                                process_id=proc.pid,
                            )
                        )
            except (psutil.AccessDenied, psutil.Error):
                pass
        except psutil.Error:
            pass


def fnmatch(path: str, pattern: str) -> bool:
    import fnmatch as _fnmatch

    return _fnmatch.fnmatch(path, pattern)
